create or replace function public.admin_set_writer_access(target_user_id uuid, writer_enabled boolean)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  actor_role public.user_role;
begin
  select role into actor_role
  from public.profiles
  where id = auth.uid();

  if actor_role is distinct from 'admin' then
    raise exception 'Only admins can update writer access';
  end if;

  update public.profiles
  set is_writer = writer_enabled
  where id = target_user_id;
end;
$$;

grant execute on function public.admin_set_writer_access(uuid, boolean) to authenticated;

create or replace function public.can_author_articles()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and (
        role = 'admin'
        or role = 'instructor'
        or is_writer = true
      )
  );
$$;

grant execute on function public.can_author_articles() to authenticated;

alter table public.articles enable row level security;

drop policy if exists "Public can read published articles" on public.articles;
create policy "Public can read published articles"
on public.articles
for select
using (status = 'published');

drop policy if exists "Authors can manage visible articles" on public.articles;
create policy "Authors can manage visible articles"
on public.articles
for select
to authenticated
using (
  status = 'published'
  or author_id = auth.uid()
  or exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  )
);

drop policy if exists "Authors can create articles" on public.articles;
create policy "Authors can create articles"
on public.articles
for insert
to authenticated
with check (
  public.can_author_articles()
  and (
    author_id = auth.uid()
    or exists (
      select 1 from public.profiles
      where id = auth.uid() and role = 'admin'
    )
  )
);

drop policy if exists "Authors can update their articles" on public.articles;
create policy "Authors can update their articles"
on public.articles
for update
to authenticated
using (
  author_id = auth.uid()
  or exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  )
)
with check (
  public.can_author_articles()
  and (
    author_id = auth.uid()
    or exists (
      select 1 from public.profiles
      where id = auth.uid() and role = 'admin'
    )
  )
);

drop policy if exists "Authors can delete their articles" on public.articles;
create policy "Authors can delete their articles"
on public.articles
for delete
to authenticated
using (
  (status = 'draft' and author_id = auth.uid())
  or exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  )
);
