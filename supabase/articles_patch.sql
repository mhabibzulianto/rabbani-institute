alter table public.profiles
  add column if not exists is_writer boolean not null default false;

create table if not exists public.articles (
  id bigint generated by default as identity primary key,
  author_id uuid not null references public.profiles(id) on delete cascade,
  category_id bigint references public.categories(id) on delete set null,
  title text not null,
  slug text not null unique,
  topic text,
  tags text[] not null default '{}'::text[],
  excerpt text,
  cover_image_url text,
  content_raw text not null default '',
  blocks jsonb not null default '[]'::jsonb,
  status text not null default 'draft' check (status in ('draft', 'submitted', 'published', 'rejected', 'archived')),
  admin_note text,
  submitted_at timestamptz,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint articles_blocks_array check (jsonb_typeof(blocks) = 'array')
);

alter table public.articles
  add column if not exists topic text,
  add column if not exists tags text[] not null default '{}'::text[],
  add column if not exists admin_note text,
  add column if not exists submitted_at timestamptz;

