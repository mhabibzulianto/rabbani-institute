begin;

create table if not exists public.institution_settings (
  id smallint primary key default 1,
  institution_name text not null default 'Rabbani Institute',
  short_name text,
  logo_url text,
  address text,
  email text,
  phone_number text,
  whatsapp_number text,
  timezone text not null default 'Asia/Jakarta',
  certificate_signatory_name text,
  certificate_signatory_title text,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint institution_settings_singleton check (id = 1)
);

insert into public.institution_settings (id)
values (1)
on conflict (id) do nothing;

create table if not exists public.academic_calendars (
  id bigint generated by default as identity primary key,
  academic_year text not null,
  semester text not null,
  name text not null,
  registration_opens_on date not null,
  registration_closes_on date not null,
  learning_starts_on date not null,
  learning_ends_on date not null,
  final_exam_starts_on date not null,
  final_exam_ends_on date not null,
  status text not null default 'draft',
  notes text,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint academic_calendars_year_semester_unique unique (academic_year, semester),
  constraint academic_calendars_status_allowed check (status in ('draft', 'active', 'archived')),
  constraint academic_calendars_registration_dates_order check (registration_opens_on <= registration_closes_on),
  constraint academic_calendars_learning_dates_order check (learning_starts_on <= learning_ends_on),
  constraint academic_calendars_final_exam_dates_order check (final_exam_starts_on <= final_exam_ends_on),
  constraint academic_calendars_exam_within_learning check (
    final_exam_starts_on >= learning_starts_on
    and final_exam_ends_on <= learning_ends_on
  )
);

create index if not exists academic_calendars_status_idx
on public.academic_calendars (status);

create or replace function public.set_master_data_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

drop trigger if exists institution_settings_set_updated_at on public.institution_settings;
create trigger institution_settings_set_updated_at
before update on public.institution_settings
for each row execute function public.set_master_data_updated_at();

drop trigger if exists academic_calendars_set_updated_at on public.academic_calendars;
create trigger academic_calendars_set_updated_at
before update on public.academic_calendars
for each row execute function public.set_master_data_updated_at();

alter table public.institution_settings enable row level security;
alter table public.academic_calendars enable row level security;

drop policy if exists "Admins manage institution settings" on public.institution_settings;
create policy "Admins manage institution settings"
on public.institution_settings
for all
to authenticated
using (
  exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'admin'
  )
)
with check (
  exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'admin'
  )
);

drop policy if exists "Admins manage academic calendars" on public.academic_calendars;
create policy "Admins manage academic calendars"
on public.academic_calendars
for all
to authenticated
using (
  exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'admin'
  )
)
with check (
  exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'admin'
  )
);

commit;
